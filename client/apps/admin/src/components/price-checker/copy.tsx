const dictionaries: Record<Language, typeof en> = { en, ha, pig };

export function keysOf(lang: Language): string[] {
  return Object.keys(dictionaries[lang]);
}

export function t(
  lang: Language,
  key: keyof typeof en,
  vars?: Record<string, string | number>
): string {
  const tables = dictionaries[lang] ?? dictionaries.en;
  const text = tables[key] ?? dictionaries.en[key] ?? String(key);
  if (!vars) return text;
  let out = text;
  for (const [name, value] of Object.entries(vars)) {
    out = out.replace(new RegExp(`\\{${name}\\}`, 'g'), String(value));
  }
  return out;
}

const LanguageContext = createContext<Language>('en');

export function LanguageProvider({ lang, children }: { lang: Language; children: ReactNode }) {
  return <LanguageContext.Provider value={lang}>{children}</LanguageContext.Provider>;
}

export function useCopy() {
  const lang = useContext(LanguageContext);
  return { lang, t: (key: keyof typeof en, vars?: Record<string, string | number>) => t(lang, key, vars) };
}
