'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const mongoose = require('mongoose');
const { uri, connectVenueMongo } = require('./helpers/venueMongo');
test('persisted listing and size override percentages survive live retail/default changes and reset to inheritance', { skip: !uri }, async t => {
  await connectVenueMongo(t, 'selling_markup');
  const Tenant = require('../models/Tenant'), SubProduct = require('../models/SubProduct'), Size = require('../models/Size');
  const { adminSetSubProductStatus } = require('../services/subproduct.service');
  const { calculateSubProductPricing, calculateSizePricing } = require('../utils/pricing');
  const tenantId = new mongoose.Types.ObjectId(), productId = new mongoose.Types.ObjectId();
  await Tenant.collection.insertOne({ _id: tenantId, name: 'Pricing fixture', revenueModel: 'selling_price_markup', sellingPriceMarkupPercentage: 20 });
  const sp = await SubProduct.create({ tenant: tenantId, product: productId, sku: 'MARKUP-TEST', baseSellingPrice: 100000, costPrice: 90000, visibleInOnlineStore: false });
  const operator = { role: 'admin' };
  await adminSetSubProductStatus(String(sp._id), 'active', { baseWebsitePrice: 125000 }, null, operator);
  assert.equal((await SubProduct.findById(sp._id)).sellingPriceMarkupOverridePct, 25);
  await SubProduct.updateOne({ _id: sp._id, tenant: tenantId }, { $set: { baseSellingPrice: 120000 } });
  await Tenant.updateOne({ _id: tenantId }, { $set: { sellingPriceMarkupPercentage: 30 } });
  const terms = await Tenant.findById(tenantId).lean();
  assert.equal(calculateSubProductPricing(await SubProduct.findById(sp._id), {}, terms).finalPrice, 150000);
  await adminSetSubProductStatus(String(sp._id), 'active', { useTenantDefault: true }, null, operator);
  assert.equal(calculateSubProductPricing(await SubProduct.findById(sp._id), {}, terms).finalPrice, 156000);
  const size = await Size.create({ tenant: tenantId, subproduct: sp._id, size: '75cl', sellingPrice: 100000, costPrice: 90000 });
  sp.sizes = [size._id]; await sp.save();
  await adminSetSubProductStatus(String(sp._id), 'active', { sizes: [{ id: String(size._id), websitePrice: 125000 }] }, null, operator);
  await Size.updateOne({ _id: size._id, tenant: tenantId }, { $set: { sellingPrice: 120000 } });
  assert.equal(calculateSizePricing(await Size.findById(size._id), {}, terms).finalPrice, 150000);
  await adminSetSubProductStatus(String(sp._id), 'active', { sizes: [{ id: String(size._id), useTenantDefault: true }] }, null, operator);
  assert.equal((await Size.findById(size._id)).sellingPriceMarkupOverridePct, null);
  assert.equal(calculateSizePricing(await Size.findById(size._id), {}, terms).finalPrice, 156000);
});
