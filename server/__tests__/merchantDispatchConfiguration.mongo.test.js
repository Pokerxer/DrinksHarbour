'use strict';
const { test } = require('node:test');
const assert = require('node:assert/strict');
const mongoose = require('mongoose');
const { uri, connectVenueMongo } = require('./helpers/venueMongo');
test('platform JWT delivery configuration reads are bounded, private and permit exact review/revoke', { skip: !uri }, async t => {
  await connectVenueMongo(t, 'dconfig');
  const oid = () => new mongoose.Types.ObjectId();
  const tenant = oid(), location = oid(), other = oid(), root = oid(), customer = oid(), staff = oid();
  await require('../models/Tenant').collection.insertOne({ _id: tenant, name: 'Synthetic merchant', secret: 'PRIVATE_TENANT' });
  await require('../models/Warehouse').collection.insertMany([{ _id: location, tenant, name: 'Origin', code: 'ORIGIN', isActive: true, contact: { phone: 'PRIVATE_PHONE' } }, { _id: other, tenant, name: 'Other', code: 'OTHER', isActive: true }]);
  await require('../models/User').collection.insertMany([{ _id: root, role: 'super_admin', status: 'active' }, { _id: customer, role: 'customer', status: 'active' }, { _id: staff, tenant, role: 'tenant_owner', status: 'active' }]);
  const previous = process.env.JWT_SECRET;
  process.env.JWT_SECRET = 'synthetic-configuration-only';
  t.after(() => previous === undefined ? delete process.env.JWT_SECRET : process.env.JWT_SECRET = previous);
  const app = require('express')(); app.use(require('express').json());
  app.use('/dispatch', require('../routes/merchantLocalDispatch.routes'));
  app.use((req, res) => res.status(404).json({ message: 'Not found' }));
  app.use((e, req, res, next) => res.status(e.statusCode || 500).json({ message: e.message }));
  const server = await new Promise(resolve => { const s = app.listen(0, '127.0.0.1', () => resolve(s)); });
  t.after(() => new Promise(resolve => server.close(resolve)));
  const call = async (actor, suffix, method = 'GET', body) => {
    const response = await fetch(`http://127.0.0.1:${server.address().port}/dispatch${suffix}`, { method, headers: { 'Content-Type': 'application/json', ...(actor ? { Authorization: `Bearer ${require('jsonwebtoken').sign({ userId: String(actor) }, process.env.JWT_SECRET)}` } : {}) }, ...(body ? { body: JSON.stringify(body) } : {}) });
    return { status: response.status, cache: response.headers.get('cache-control'), body: await response.json() };
  };
  const list = await call(root, '/configuration/locations?limit=1');
  assert.equal(list.status, 200, 'configuration location read exists');
  assert.equal(list.cache, 'private, no-store');
  assert.equal(list.body.data.locations.length, 1);
  assert.equal(list.body.data.pagination.total, 2);
  assert.equal(JSON.stringify(list.body).includes('PRIVATE_'), false);
  for (const actor of [customer, staff]) assert.equal((await call(actor, '/configuration/locations')).status, 403);
  assert.equal((await call(null, '/configuration/locations')).status, 401);
  assert.equal((await call(root, '/configuration/locations?limit=999')).status, 400);
  assert.equal((await call(root, `/configuration/${oid()}/${location}`)).status, 404);
  const path = `/configuration/${tenant}/${location}`;
  assert.equal((await call(root, path)).body.data.state, 'unavailable');
  const input = { tenant: String(tenant), location: String(location), version: 1, currency: 'NGN', amountMinor: 1234, maxUnits: 5, maxWeightGrams: 6000, vehicleTypes: ['bike'], coverage: [{ country: 'NG', state: 'FCT', city: 'Abuja', minLat: 9, maxLat: 9.1, minLon: 7, maxLon: 7.5 }], capabilities: { alcohol: false, ageVerification: false, fragile: true }, reviewReference: 'synthetic explicit evidence', validUntil: new Date(Date.now() + 86400000).toISOString() };
  assert.equal((await call(staff, '/contracts', 'POST', input)).status, 403);
  assert.equal((await call(root, '/contracts', 'POST', { ...input, coverage: [null] })).status, 400);
  const saved = await call(root, '/contracts', 'POST', input);
  assert.equal(saved.status, 201);
  assert.equal((await call(root, '/contracts', 'POST', input)).status, 409);
  const id = saved.body.data.contract._id;
  await require('../models/MerchantLocalDispatchContract').collection.updateOne({ _id: id }, { $set: { 'coverage.0.secret': 'PRIVATE_COVERAGE', 'coverage.0.country': { nested: 'PRIVATE_NESTED_SCALAR' }, 'capabilities.secret': 'PRIVATE_CAPABILITY', arbitrarySecret: 'PRIVATE_ROW' } });
  const read = await call(root, `${path}?limit=1`);
  assert.equal(read.body.data.state, 'reviewed');
  assert.equal(read.body.data.latest.amountMinor, 1234);
  assert.equal(read.body.data.contracts.length, 1);
  assert.equal(JSON.stringify(read.body).includes('PRIVATE_'), false);
  assert.equal(Object.hasOwn(read.body.data.latest, 'reviewedBy'), false);
  const revoked = await call(root, `/contracts/${id}/revoke`, 'POST', {});
  assert.equal(revoked.status, 200);
  const firstRevocation = await require('../models/MerchantLocalDispatchContract').findById(id).lean();
  await new Promise(resolve => setTimeout(resolve, 5));
  await call(root, `/contracts/${id}/revoke`, 'POST', {});
  assert.equal((await require('../models/MerchantLocalDispatchContract').findById(id)).revokedAt.getTime(), firstRevocation.revokedAt.getTime(), 'repeat revocation preserves original evidence');
  assert.equal(JSON.stringify(revoked.body).includes('PRIVATE_'), false);
  assert.equal((await call(root, path)).body.data.state, 'revoked');
  assert.equal((await call(staff, `/contracts/${id}/revoke`, 'POST', {})).status, 403);
});
