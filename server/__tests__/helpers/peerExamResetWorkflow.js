const assert = require('node:assert/strict');
const mongoose = require('mongoose');
const Department = require('../../models/Department');
const User = require('../../models/User');
const Attempt = require('../../models/PeerAppraisalExamAttempt');
const P = require('../../models/PeerAppraisalParticipant');
const Audit = require('../../models/AuditLog');
module.exports = async function ({ call, ownerId, ids, tenantId, foreignId, foreignTenant }) {
  const dept = new mongoose.Types.ObjectId();
  await Department.collection.insertOne({ _id: dept, tenant: tenantId, name: 'Reset exam team', isActive: true });
  await User.collection.updateMany({ _id: { $in: ids }, tenant: tenantId }, { $set: { 'employeeProfile.work.department': dept } });
  const created = await call(ownerId, '', 'POST', { name: 'Owner reset test' });
  const path = `/${created.body.data._id}`;
  await call(ownerId, `${path}/participants`, 'PUT', { expectedRevision: 0, participants: ids.map(employee => ({ employee: String(employee), bonusAmount: 100 })) });
  await call(ownerId, `${path}/examination`, 'PUT', { expectedRevision: 1, durationMinutes: 8, attendanceFrom: '2020-01-01', attendanceTo: '2020-01-31', recipientIds: [String(ids[0])], departments: [String(dept)], questions: [{ prompt: 'Reset question', options: ['Yes', 'No'], correctOption: 0, marks: 2 }] });
  await call(ownerId, `${path}/launch`, 'POST');
  const started = (await call(ids[0], `${path}/examination/start`, 'POST')).body.data;
  const submitted = await call(ids[0], `${path}/examination/submit`, 'POST', { expectedRevision: started.revision, answers: started.questions.map(q => ({ question: q.question, option: 0 })) });
  assert.equal(submitted.status, 200);
  const progress = (await call(ownerId, `${path}/participants`)).body.data;
  const attempt = progress.examination.attempts[0];
  assert.equal(attempt.employee, String(ids[0]));
  assert.equal(JSON.stringify(attempt).includes('answers'), false);
  const endpoint = `${path}/examination/attempts/${ids[0]}/reset`;
  const body = { expectedRevision: attempt.revision, expectedCycleRevision: progress.revision };
  assert.equal((await call(null, endpoint, 'POST', body)).status, 401);
  assert.equal((await call(ids[0], endpoint, 'POST', body)).status, 403);
  assert.equal((await call(ownerId, `${path}/examination/attempts/bad/reset`, 'POST', body)).status, 400);
  assert.equal((await call(ownerId, `${path}/examination/attempts/${foreignId}/reset`, 'POST', body)).status, 404);
  assert.equal((await call(ownerId, `${path}/examination/attempts/${ids[1]}/reset`, 'POST', body)).status, 404);
  const foreignOwner = new mongoose.Types.ObjectId();
  await User.collection.insertOne({ _id: foreignOwner, tenant: foreignTenant, role: 'tenant_owner', status: 'active', firstName: 'Foreign reset owner' });
  assert.equal((await call(foreignOwner, endpoint, 'POST', body)).status, 404);
  assert.equal((await call(ownerId, endpoint, 'POST', { ...body, expectedRevision: 0 })).status, 409);
  assert.equal((await call(ownerId, endpoint, 'POST', { ...body, expectedCycleRevision: 0 })).status, 409);
  const scope = { tenant: tenantId, cycle: new mongoose.Types.ObjectId(created.body.data._id), employee: ids[0] };
  const before = await Attempt.findOne(scope).lean();
  assert.equal((await call(ownerId, endpoint, 'POST', body)).status, 200);
  const after = await Attempt.findOne(scope).lean();
  assert.deepEqual(after.answers, []); assert.equal(after.revision, before.revision + 1);
  assert.deepEqual(after.questionIds, before.questionIds); assert.equal(after.durationMinutes, 8);
  for (const key of ['startedAt', 'expiresAt', 'submittedAt', 'timedOut', 'earnedMarks', 'maxMarks', 'correctCount', 'questionCount']) assert.equal(after[key], undefined);
  assert.equal(await Audit.countDocuments({ action: 'PEER_EXAM_ATTEMPT_RESET', targetId: after._id, targetTenantId: tenantId, actorUserId: ownerId }), 1);
  assert.equal((await call(ids[0], `${path}/examination`, 'PATCH', { expectedRevision: before.revision, answers: [] })).status, 409);
  assert.equal((await call(ownerId, endpoint, 'POST', body)).status, 409);
  const restarted = (await call(ids[0], `${path}/examination/start`, 'POST')).body.data;
  assert.equal(new Date(restarted.expiresAt) - new Date(restarted.startedAt), 8 * 60000);
  const fresh = (await call(ownerId, `${path}/participants`)).body.data;
  const nextBody = { expectedRevision: restarted.revision, expectedCycleRevision: fresh.revision };
  await P.collection.updateOne(scope, { $set: { result: { averageScore: 5 } } });
  assert.equal((await call(ownerId, endpoint, 'POST', nextBody)).status, 409);
  await P.collection.updateOne(scope, { $unset: { result: '' } });
  await call(ownerId, `${path}/cancel`, 'POST');
  assert.equal((await call(ownerId, endpoint, 'POST', nextBody)).status, 409);
};
