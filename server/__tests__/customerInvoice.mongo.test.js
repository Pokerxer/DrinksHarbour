const test = require('node:test');
const assert = require('node:assert/strict');
const mongoose = require('mongoose');
const uri = process.env.DRINKSHARBOUR_SAVED_INVOICE_TEST_MONGO_URI;
test('saved invoices have stable identities, immutable posted snapshots and reuse existing postings', { skip: !uri }, async (t) => {
  assert.match(uri, /^mongodb:\/\/127\.0\.0\.1:\d+\/drinks_saved_invoice_test_[\w]+$/);
  await mongoose.connect(uri, { autoIndex: false, serverSelectionTimeoutMS: 5000 });
  t.after(async () => { await mongoose.connection.dropDatabase(); await mongoose.disconnect(); });
  const SalesOrder = require('../models/SalesOrder');
  const Journal = require('../models/JournalEntry');
  const sync = require('../services/customerInvoice/sync');
  const Invoice = require('../models/CustomerInvoice');
  await Invoice.createIndexes();
  await require('../models/InvoiceCounter').createIndexes();
  const tenant = new mongoose.Types.ObjectId(), other = new mongoose.Types.ObjectId();
  const source = new mongoose.Types.ObjectId();
  await SalesOrder.collection.insertOne({ _id: source, tenant, soNumber: 'SO-1', docType: 'order', orderStatus: 'fulfilled', currency: 'NGN', total: 100, subtotal: 100, amountPaid: 0,
    items: [{ name: 'Wine', quantity: 1, unitPrice: 100, lineType: 'product', subproduct: new mongoose.Types.ObjectId() }], createdAt: new Date('2026-10-13') });
  await Journal.collection.insertOne({ tenant, refDoc: source, refDocType: 'SalesOrder', entryType: 'sales_revenue', status: 'posted', lines: [{ account: '1300', debit: 100, credit: 0 }, { account: '4000', debit: 0, credit: 100 }] });
  const first = await sync.syncSource({ tenantId: tenant, source: 'sales', sourceId: source });
  assert.match(first.number, /^INV-2026-\d+$/);
  assert.equal(first.state, 'posted');
  assert.equal(first.paymentStatus, 'unpaid');
  assert.equal(String(first.sourceId), String(source));
  const again = await sync.syncSource({ tenantId: tenant, source: 'sales', sourceId: source });
  assert.equal(String(again._id), String(first._id));
  assert.equal(await Invoice.countDocuments({ tenant }), 1);
  assert.equal(await Journal.countDocuments({ tenant }), 1);
  assert.equal(await sync.syncSource({ tenantId: other, source: 'sales', sourceId: source }), null);
  await SalesOrder.collection.updateOne({ _id: source }, { $set: { total: 200, 'items.0.unitPrice': 200 } });
  const changed = await sync.syncSource({ tenantId: tenant, source: 'sales', sourceId: source });
  assert.equal(changed.total, 100);
  assert.equal(changed.items[0].unitPrice, 100);
  assert.match(changed.reconciliationIssue, /changed/i);
  await assert.rejects(Invoice.updateOne({ _id: first._id, tenant }, { $set: { total: 999 } }), /cannot be changed/);
  const missing = new mongoose.Types.ObjectId();
  const original = await SalesOrder.collection.findOne({ _id: source });
  await SalesOrder.collection.insertOne({ ...original, _id: missing, soNumber: 'SO-2' });
  const draft = await sync.syncSource({ tenantId: tenant, source: 'sales', sourceId: missing });
  assert.equal(draft.state, 'draft');
  assert.match(draft.reconciliationIssue, /missing/);
  const { listInvoices, getInvoice } = require('../services/customerInvoice/browse');
  const page = await listInvoices(tenant, {});
  assert.equal(page.total, 2);
  assert.equal(page.data[0].orderNumber.startsWith('INV-'), true);
  await assert.rejects(getInvoice(other, first._id), /not found/);
  const open = await listInvoices(tenant, { scope: 'open' });
  assert.equal(open.total, 0); // Changed posted source must be reconciled first.
  const { importInvoices } = require('../services/customerInvoice/import');
  const before = await Invoice.countDocuments();
  const dryRun = await importInvoices({ tenantId: tenant });
  assert.equal(dryRun.existing, 2);
  assert.equal(await Invoice.countDocuments(), before);
  await importInvoices({ tenantId: tenant, apply: true });
  await importInvoices({ tenantId: tenant, apply: true });
  assert.equal(await Invoice.countDocuments(), before);
  await require('./fixtures/saved-invoice-scenarios').fifoAndLinked(tenant);
  await require('./fixtures/saved-invoice-scenarios').manualIssueAndPayments(tenant);
  await require('./fixtures/invoice-detail-records').verifyDetailRead(tenant, other, first);
});
