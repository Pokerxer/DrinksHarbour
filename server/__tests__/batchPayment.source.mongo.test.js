const test = require('node:test');
const assert = require('node:assert/strict');
const mongoose = require('mongoose');
const uri = process.env.SOURCE_BATCH_TEST_URI;
test('source batches claim Cash/Wallet independently, prevent duplicate owners and retain cancelled history without financial writes', { skip: !uri }, async (t) => {
  assert.match(uri, /^mongodb:\/\/127\.0\.0\.1:\d+\/drinks_source_batches_test_\w+$/);
  await mongoose.connect(uri, { autoIndex: false, serverSelectionTimeoutMS: 5000 });
  t.after(async () => { await mongoose.connection.dropDatabase(); await mongoose.disconnect(); });
  const db = mongoose.connection.db;
  const { ids } = await require('./fixtures/invoice-return-records').seed(db);
  const entry = await db.collection('journalentries').findOne({ tenant: ids.tenant, refDoc: ids.pos, entryType: 'customer_payment' });
  await db.collection('journalentries').updateOne({ _id: entry._id }, { $set: { lines: [{ account: '1000', debit: 40 }, { account: '2200', debit: 60 }, { account: '1300', credit: 100 }] } });
  const service = require('../services/batchPayment.service');
  const input = { tenantId: ids.tenant, direction: 'customer', account: '2200', paymentIds: [`source:${entry._id}:2200`], userId: ids.customer };
  const manual = await require('../services/accountingPayment.service').createPayment({ tenantId: ids.tenant, direction: 'customer', userId: ids.customer, data: { customer: ids.customer, amount: 25, method: 'bank_transfer', allocations: [] } });
  const invalidPayment = new mongoose.Types.ObjectId();
  await db.collection('customerpayments').insertOne({ _id: invalidPayment, tenant: ids.tenant, customerName: 'Invalid posting', number: 'INVALID-PAYMENT', amount: 5, method: 'bank_transfer', status: 'active', batch: null, allocations: [] });
  await db.collection('journalentries').insertOne({ tenant: ids.tenant, refDoc: invalidPayment, refDocType: 'CustomerPayment', entryType: 'customer_payment', status: 'posted', lines: [{ account: '1100', debit: 5 }, { account: '4000', credit: 5 }] });
  assert.equal((await service.listUnbatched(ids.tenant, 'customer', { account: '1100' })).data.some(row => row.paymentId === String(invalidPayment)), false);
  const financialBefore = await db.collection('journalentries').countDocuments({});
  const paymentsBefore = await db.collection('customerpayments').countDocuments({});
  await assert.rejects(service.createBatch(input), /index|protection/i);
  await db.collection('sourcebatchclaims').createIndex({ tenant: 1, journal: 1, account: 1 }, { unique: true, partialFilterExpression: { active: true }, name: 'source_account_active_unique' });
  await assert.rejects(service.createBatch({ ...input, expectedMembers: [{ key: input.paymentIds[0], capturedAmount: 60, refundedAmount: 0, amount: 59 }] }), /changed|amount/i);
  const outcomes = await Promise.allSettled([service.createBatch(input), service.createBatch(input)]);
  assert.equal(outcomes.filter(r => r.status === 'fulfilled').length, 1);
  const wallet = outcomes.find(r => r.status === 'fulfilled').value;
  assert.equal(wallet.total, 60);
  const bank = await service.createBatch({ ...input, account: '1100', paymentIds: [String(manual._id)] });
  assert.equal(bank.total, 25);
  assert.equal(String((await db.collection('customerpayments').findOne({ _id: manual._id })).batch), String(bank._id));
  await service.cancelBatch({ tenantId: ids.tenant, id: bank._id });
  assert.equal((await db.collection('customerpayments').findOne({ _id: manual._id })).batch, null);
  assert.equal((await db.collection('customerpayments').findOne({ _id: manual._id })).status, 'active');
  // Legacy bank-deposit batches used a destination account independent of tender.
  const Batch = require('../models/BatchPayment');
  const legacy = await Batch.create({ tenant: ids.tenant, number: 'LEGACY-CASH-DESTINATION', direction: 'customer', account: '1000', total: 25 });
  await db.collection('customerpayments').updateOne({ _id: manual._id }, { $set: { batch: legacy._id } });
  await service.depositBatch({ tenantId: ids.tenant, id: legacy._id });
  const legacySaved = await db.collection('batchpayments').findOne({ _id: legacy._id });
  assert.equal(legacySaved.status, 'deposited');
  assert.equal(legacySaved.membershipVersion, 1);
  assert.equal(legacySaved.members[0].amount, 25);
  assert.equal(legacySaved.account, '1000');
  const unknownHistory = await Batch.create({ tenant: ids.tenant, number: 'LEGACY-CANCELLED', direction: 'customer', account: '1100', total: 123, status: 'cancelled' });
  const old = (await service.listBatches(ids.tenant, { status: 'cancelled' })).data.find(row => String(row._id) === String(unknownHistory._id));
  assert.equal(old.historyAvailable, false);
  assert.equal(old.total, 123);

  assert.equal(await db.collection('sourcebatchclaims').countDocuments({ tenant: ids.tenant, journal: entry._id, account: '2200', active: true }), 1);
  const cash = await service.createBatch({ ...input, account: '1000', paymentIds: [`source:${entry._id}:1000`] });
  assert.equal(cash.total, 40);
  await assert.rejects(service.createBatch({ ...input, tenantId: ids.other }), /eligible/i);
  await service.cancelBatch({ tenantId: ids.tenant, id: wallet._id });
  const cancelled = (await service.listBatches(ids.tenant, { status: 'cancelled' })).data.find(b => String(b._id) === String(wallet._id));
  assert.equal(cancelled.members[0].amount, 60); assert.equal(cancelled.total, 60);
  const rebuilt = await service.createBatch(input);
  await db.collection('orders').updateOne({ _id: ids.pos }, { $set: { refunds: [{ _id: ids.refund, totalRefunded: 10 }] } });
  await db.collection('journalentries').insertOne({ tenant: ids.tenant, refDoc: ids.refund, refDocType: 'OrderRefund', entryType: 'refund', status: 'posted', lines: [{ account: '1300', debit: 10 }, { account: '2200', credit: 10 }] });
  await assert.rejects(service.depositBatch({ tenantId: ids.tenant, id: rebuilt._id }), /changed|review/i);
  await service.cancelBatch({ tenantId: ids.tenant, id: rebuilt._id });
  const net = await service.createBatch(input); assert.equal(net.total, 50);
  await service.depositBatch({ tenantId: ids.tenant, id: net._id });
  await assert.rejects(service.createBatch(input), /eligible/i);
  await assert.rejects(service.cancelBatch({ tenantId: ids.tenant, id: net._id }), /open/i);
  await assert.rejects(service.depositBatch({ tenantId: ids.other, id: cash._id }), /open/i);
  assert.equal(await db.collection('customerpayments').countDocuments({}), paymentsBefore);
  assert.equal(await db.collection('journalentries').countDocuments({}), financialBefore + 1); // only explicit test refund
  assert.equal((await db.collection('salesorders').findOne({ _id: ids.sales })).amountPaid, 100);
});
