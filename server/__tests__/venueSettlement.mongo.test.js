'use strict';
const test = require('node:test'); const assert = require('node:assert/strict'); const mongoose = require('mongoose');
const { uri, connectVenueMongo, fixture, beverage } = require('./helpers/venueMongo');
test('cash_retry_settles_one_receipt_stock_issue_journal_set_and_table_release', { skip: !uri }, async t => {
  await connectVenueMongo(t, 'settle');
  const sessions = require('../services/venue/service-sessions'); await sessions.ensureIndexes();
  const billing = require('../services/venue/billing'); await billing.ensureIndexes();
  const payments = require('../services/venue/collections'); await payments.ensureIndexes();
  const args = await fixture(); const input = await beverage(args);
  const drawer = new mongoose.Types.ObjectId();
  await require('../models/POSSession').collection.insertOne({ _id: drawer, tenant: new mongoose.Types.ObjectId(args.tenantId), warehouse: new mongoose.Types.ObjectId(args.locationId), status: 'open', shopId: 'retail' });
  await require('../services/chartOfAccounts.service').ensureDefaultCOA(args.tenantId);
  await require('../models/JournalEntry').createIndexes();
  args.posSessionId = String(drawer);
  const visit = await sessions.ensureServiceSession({ ...args, idempotencyKey: 'open' });
  const accepted = await require('../services/venue/lines').setSessionLines({ ...args, sessionId: visit.id, expectedVersion: visit.version, lines: [input], idempotencyKey: 'lines' });
  const bill = await billing.ensureBillOrder({ ...args, sessionId: visit.id, expectedVersion: accepted.version, lineVersion: accepted.lineVersion, ageVerified: true, idempotencyKey: 'bill' });
  const command = { ...args, sessionId: visit.id, expectedVersion: bill.version, quoteId: bill.quoteId, method: 'cash', amountTenderedMinor: 400000, idempotencyKey: 'cash' };
  const first = await payments.collectBill(command); const again = await payments.collectBill(command);
  assert.equal(first.bill.state, 'settled'); assert.equal(again.bill.state, 'settled');
  assert.equal(first.changeMinor, 100000);
  assert.equal(await require('../models/VenuePaymentReceipt').countDocuments({ tenant: args.tenantId }), 1);
  assert.equal(await require('../models/VenuePaymentAllocation').countDocuments({ tenant: args.tenantId }), 1);
  assert.equal(await require('../models/JournalEntry').countDocuments({ tenant: args.tenantId, refDoc: bill.orderId }), 2);
  assert.equal(await require('../models/WarehouseMovement').countDocuments({ tenant: args.tenantId, type: 'shipped' }), 1);
  const stock = await require('../models/WarehouseStock').findOne({ tenant: args.tenantId }).lean();
  assert.equal(stock.currentQuantity, 7); assert.equal(stock.reservedQuantity, 2);
  const table = await require('../models/POSTable').findOne({ _id: args.tableIds[0] }).lean(); assert.equal(table.currentTabId, null); assert.equal(table.status, 'available');
  const totals = await require('../services/posSessionTotals.service').getSessionOrderStats(args.tenantId, String(drawer)); assert.equal(totals.orderCount, 1);
});
