'use strict';
const test = require('node:test'); const assert = require('node:assert/strict'); const mongoose = require('mongoose');
const { uri, connectVenueMongo, fixture, beverage } = require('./helpers/venueMongo');
test('experience config is scoped, versioned, publication-reviewed and layout cannot change occupancy', {skip:!uri}, async t => {
  await connectVenueMongo(t,'experience'); const args = await fixture();
  const api = require('../services/venue/experience');
  await require('../services/venue/service-sessions').ensureIndexes();
  await require('../models/VenueLocationProfile').createIndexes();
  const profile = {slug:'main',name:'Main lounge',types:['lounge'],timezone:'Africa/Lagos',description:'Beverages',address:'Abuja',hours:[],exceptions:[],policies:'Request only; staff seating at arrival'};
  const first = await api.saveConfiguration({...args,kind:'profile',expectedVersion:0,input:profile,idempotencyKey:'profile'});
  assert.equal(first.version,1); assert.equal(first.publication,'draft');
  assert.deepEqual(await api.saveConfiguration({...args,kind:'profile',expectedVersion:0,input:profile,idempotencyKey:'profile'}),first);
  await assert.rejects(api.saveConfiguration({...args,kind:'profile',expectedVersion:0,input:profile,idempotencyKey:'stale'}),/changed/i);
  await assert.rejects(api.getConfiguration({...args,actor:{...args.actor,tenantId:String(new mongoose.Types.ObjectId())}}),/not found/i);
  const other = await fixture(); await assert.rejects(api.getConfiguration({...args,locationId:other.locationId}),/not found/i);
  const floor = {zones:[{id:'main',name:'Main room'}],tables:[{tableId:args.tableIds[0],zone:'main',x:20,y:30,shape:'round'}]};
  const changes = await Promise.allSettled([1,2].map(n=>api.saveConfiguration({...args,kind:'floor',expectedVersion:1,input:floor,idempotencyKey:`floor-${n}`})));
  assert.equal(changes.filter(r=>r.status==='fulfilled').length,1);
  const table = await require('../models/POSTable').findOne({_id:args.tableIds[0]}).lean();
  assert.equal(table.status,'available'); assert.equal(table.currentTabId,null); assert.equal(table.venueVersion,0);
  const line = await beverage(args);
  const sp=await require('../models/SubProduct').findById(line.subProductId);
  await require('../models/Product').collection.updateOne({_id:sp.product},{$set:{status:'approved',isPublished:true}});
  const menu = {sections:[{id:'drinks',name:'Drinks',items:[{subProductId:line.subProductId,sizeId:line.sizeId,published:true}]}]};
  await api.saveConfiguration({...args,kind:'menu',expectedVersion:2,input:menu,idempotencyKey:'menu'});
  const projection = await api.readMenu(args);
  const candidates = await api.menuCandidates(args);
  assert.equal(candidates.items[0].id, line.subProductId);
  assert.equal(candidates.items[0].sizes[0].id, line.sizeId);
  assert.equal(projection.sections[0].items[0].unitPriceMinor,100000);
  assert.equal(projection.sections[0].items[0].available,true);
  const publicText=JSON.stringify(projection); for(const secret of ['costPrice','costMinor','reservedQuantity','currentQuantity','venueStaff']) assert.equal(publicText.includes(secret),false);
  await require('../models/Tenant').updateOne({_id:args.tenantId},{$set:{subscriptionStatus:'past_due'}});
  assert.equal((await api.workspace(args)).canManage,false);
  assert.equal((await api.workspace(args)).canReview,false);
  await require('../models/Tenant').updateOne({_id:args.tenantId},{$set:{subscriptionStatus:'cancelled'}});
  await assert.rejects(api.saveConfiguration({...args,kind:'floor',expectedVersion:3,input:floor,idempotencyKey:'lapsed'}),/not available/i);
});
