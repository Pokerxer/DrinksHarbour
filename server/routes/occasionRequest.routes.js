'use strict';
const router=require('express').Router(),multer=require('multer'),rateLimit=require('express-rate-limit');
const {protect,authorize}=require('../middleware/auth.middleware');
const c=require('../controllers/occasionRequest.controller');
const chat=require('../controllers/occasionConversation.controller');
const limiter=(max,windowMs)=>rateLimit({max,windowMs,standardHeaders:true,legacyHeaders:false,validate:{xForwardedForHeader:false,forwardedHeader:false},message:{success:false,message:'Too many requests. Please try again later.'}});
const upload=multer({storage:multer.memoryStorage(),limits:{fileSize:8*1024*1024,files:1,fields:1,fieldSize:24000}}).single('file');
router.use(protect);
router.use((req,res,next)=>{res.set('Cache-Control','no-store');next();});
router.post('/',authorize('customer'),limiter(5,30*60*1000),(req,res,next)=>upload(req,res,error=>error?res.status(400).json({success:false,message:'Choose one supported list document up to 8 MB or photo up to 5 MB.'}):next()),c.submit);
router.get('/mine',authorize('customer'),chat.list);
router.get('/mine/:id/file',authorize('customer'),chat.file);
router.get('/:id/messages',authorize('customer','admin','super_admin'),chat.read);
router.post('/:id/messages',authorize('customer'),limiter(20,10*60*1000),chat.send);
router.use(authorize('admin','super_admin'));
router.use((req,res,next)=>{res.set('Cache-Control','no-store');next();});
router.get('/',c.list);router.get('/:id/file',c.file);router.get('/:id',c.detail);
router.patch('/:id/draft',c.save);
router.post('/:id/generate',limiter(10,15*60*1000),c.generate);
router.post('/:id/send',limiter(10,15*60*1000),c.send);
router.post('/:id/record-whatsapp',c.recordWhatsApp);
router.post('/:id/publish',c.publishChat);
module.exports=router;
