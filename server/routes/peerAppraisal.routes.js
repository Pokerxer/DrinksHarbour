const router = require('express').Router();
const { protect, attachTenant, requireOwnTenant } = require('../middleware/auth.middleware');
const c = require('../controllers/peerAppraisal.controller');
const exam = require('../controllers/peerExamination.controller');
const { rateLimit } = require('express-rate-limit');
const generateLimit = rateLimit({ windowMs: 15 * 60 * 1000, limit: 5, keyGenerator: req => `${req.user.tenant}:${req.user._id}`, standardHeaders: true, legacyHeaders: false, message: { success: false, message: 'Too many question generation requests. Try again later.' } });
router.use(protect, attachTenant, requireOwnTenant);
router.get('/my', c.my);
router.get('/eligible-employees', c.eligible);
router.post('/', c.create);
router.get('/:cycleId/examination/bank/:bankId', exam.bank);
router.post('/:cycleId/examination/generate', generateLimit, exam.generate);
router.put('/:cycleId/examination', exam.configure);
router.get('/:cycleId/examination', exam.own);
router.post('/:cycleId/examination/start', exam.start);
router.patch('/:cycleId/examination', exam.draft);
router.post('/:cycleId/examination/submit', exam.submit);
router.get('/:cycleId/review', c.review);
router.patch('/:cycleId/review', c.save);
router.post('/:cycleId/submit', c.submit);
router.get('/:cycleId/result', c.result);
router.get('/:cycleId/participants', c.participants);
router.put('/:cycleId/participants', c.replace);
router.post('/:cycleId/launch', c.launch);
router.post('/:cycleId/close', c.close);
router.post('/:cycleId/cancel', c.cancel);
module.exports = router;
